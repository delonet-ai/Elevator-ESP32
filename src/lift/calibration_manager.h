#pragma once
#include <Arduino.h>

// Расчёт геометрии шахты по результатам калибровки.
//
// Порядок: доехали вверх до концевика -> calibMarkTop() -> спустились
// в самый низ -> calibFinishAtBottom(). Управление движением и состояниями
// остаётся в автомате, здесь только арифметика и сохранение.

void calibInit();

// Есть ли пригодная калибровка.
bool calibIsValid();

// Концевик достигнут: принимаем эту точку за 0 калибровочной шкалы.
void calibMarkTop();

// Кабина внизу. bottomPos — позиция в калибровочной шкале (отрицательная).
// Возвращает false, если измеренный ход меньше допустимого: калибровка
// в этом случае не сохраняется.
bool calibFinishAtBottom(long bottomPos);

// Стереть калибровку, в том числе из NVS.
void calibReset();
