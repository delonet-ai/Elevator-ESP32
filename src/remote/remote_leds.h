//   нужна калибровка   — мигает UP (подсказка «нажми вверх»);
//   калибровка вниз    — UP горит, мигает F1 (подсказка «зафиксируй низ»);
//   нужен хоминг       — мигает UP;
//   стоим на этаже     — мигает кнопка этого этажа;
//   едем               — ровно горит кнопка целевого этажа.

